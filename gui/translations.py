# Текущий язык интерфейса (глобальная переменная)
_current_ui_language = 'Russian'


def set_ui_language(language: str):
    """Установить язык интерфейса"""
    global _current_ui_language
    if language in TRANSLATIONS:
        _current_ui_language = language
    elif language in UI_LANGUAGES_REVERSE:
        _current_ui_language = UI_LANGUAGES_REVERSE[language]


def get_ui_language() -> str:
    """Получить текущий язык интерфейса"""
    return _current_ui_language


def get_ui_translation_report(language: Optional[str] = None) -> Dict[str, dict]:
    """Return explicit catalog coverage without counting English fallback.

    The missing key list is deterministic and suitable for CI output or for
    generating a translator review worksheet.
    """
    languages = [language] if language else list(UI_LANGUAGES)
    report = {}
    total = len(_ENGLISH_TRANSLATION_KEYS)
    for locale in languages:
        explicit = _EXPLICIT_TRANSLATION_KEYS.get(locale, frozenset())
        missing = sorted(_ENGLISH_TRANSLATION_KEYS - explicit)
        report[locale] = {
            'total': total,
            'explicit': total - len(missing),
            'missing_count': len(missing),
            'coverage': (total - len(missing)) / max(1, total),
            'missing_keys': missing,
            'complete': not missing,
        }
    return report


def _translation_format_signature(value: str) -> Counter:
    """Return the complete ``str.format`` contract used by a UI string."""
    return Counter(
        (field_name, format_spec, conversion)
        for _literal, field_name, format_spec, conversion in Formatter().parse(
            str(value)
        )
        if field_name is not None
    )


_PRINTF_TOKEN_RE = re.compile(
    r'%(?:\([^)]+\))?[#0\-+]?(?:\d+|\*)?(?:\.(?:\d+|\*))?'
    r'[hlL]?[diouxXeEfFgGcrsa%]'
)
_MARKUP_TOKEN_RE = re.compile(r'<\s*(/?)\s*([A-Za-z][\w:-]*)(?:\s[^>]*)?(/?)\s*>')


def _translation_percent_signature(value: str) -> Counter:
    """Return printf-style tokens while ignoring ordinary percentage signs."""
    return Counter(_PRINTF_TOKEN_RE.findall(str(value)))


def _translation_markup_signature(value: str) -> Counter:
    """Return the structural HTML/XML tag contract of a translated string."""
    return Counter(
        (bool(closing), tag.casefold(), bool(self_closing))
        for closing, tag, self_closing in _MARKUP_TOKEN_RE.findall(str(value))
    )


def get_ui_translation_format_issues(languages=None) -> Dict[str, list]:
    """Report placeholder/newline drift that would break localized widgets."""
    selected = tuple(languages or UI_LANGUAGES)
    english = TRANSLATIONS['English']
    issues = {}
    for locale in selected:
        catalog = TRANSLATIONS.get(locale, {})
        locale_issues = []
        for key, english_value in english.items():
            translated = catalog.get(key, '')
            if _translation_format_signature(translated) != _translation_format_signature(
                english_value
            ):
                locale_issues.append((key, 'placeholders'))
            if _translation_percent_signature(translated) != _translation_percent_signature(
                english_value
            ):
                locale_issues.append((key, 'printf'))
            if _translation_markup_signature(translated) != _translation_markup_signature(
                english_value
            ):
                locale_issues.append((key, 'markup'))
            if str(translated).count('\n') != str(english_value).count('\n'):
                locale_issues.append((key, 'newlines'))
        if locale_issues:
            issues[locale] = locale_issues
    return issues


def validate_ui_translation_catalogs(languages=None) -> None:
    """Raise when a locale is incomplete or breaks a formatting contract."""
    selected = tuple(languages or UI_LANGUAGES)
    incomplete = {
        locale: data['missing_keys']
        for locale, data in get_ui_translation_report().items()
        if locale in selected and data['missing_keys']
    }
    if incomplete:
        summary = '; '.join(
            f"{locale}: {len(keys)} missing ({', '.join(keys[:8])}"
            f"{'…' if len(keys) > 8 else ''})"
            for locale, keys in incomplete.items()
        )
        raise ValueError(f"Incomplete UI translation catalogs: {summary}")

    format_issues = get_ui_translation_format_issues(selected)
    if format_issues:
        summary = '; '.join(
            f"{locale}: {len(issues)} format issue(s) "
            f"({', '.join(f'{key}/{kind}' for key, kind in issues[:8])}"
            f"{'…' if len(issues) > 8 else ''})"
            for locale, issues in format_issues.items()
        )
        raise ValueError(f"Invalid UI translation formatting: {summary}")


def t(key: str, language: Optional[str] = None) -> str:
    """
    Получить перевод по ключу.
    
    Args:
        key: Ключ перевода
        language: Язык (если None - используется текущий)
        
    Returns:
        Переведённая строка или ключ если перевод не найден
    """
    lang = language or _current_ui_language
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS.get('English', {}))
    return lang_dict.get(key, TRANSLATIONS['English'].get(key, key))


