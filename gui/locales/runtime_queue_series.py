def _catalog(
    messages: dict[str, str],
    fields: dict[str, str],
    sections: dict[str, str],
    values: dict[str, str],
) -> dict[str, str]:
    catalog = dict(messages)
    catalog.update(values)
    catalog.update({key: f"   {label}: {{value}}" for key, label in fields.items()})
    catalog.update(sections)
    return catalog


